#!/usr/bin/env python3
"""Scenario C: generates the 100-rule pricing decision table (hit policy COLLECT, aggregation SUM) for every engine,
plus the same rules as JSON so the k6 script can compute the expected fee for each request.

Rules 1-99 are random (fixed seed) ranges/values on age, amount, country and customerType, fee = rule number.
Rule 100 matches everything with fee 1000, so the sum is never empty (COLLECT SUM over no hits returns null).
Every request is checked against all 100 rules, whichever ones match.

Dialects: FEEL for the C7 forks (typeRef integer), Kogito and Camunda 8 (typeRef number); Flowable has no FEEL ranges,
so its table splits age and amount into a ">=" and a "<=" column each.
Usage: python3 load/gen-pricing-dmn.py   (from the repo root; overwrites the generated files)
"""
import json
import random
from pathlib import Path

COUNTRIES = ["DE", "AT", "CH", "FR", "NL"]
TYPES = ["standard", "premium", "business", "student"]
NS = "http://example.com/bench/pricing"


def make_rules():
    rnd = random.Random(42)
    rules = []
    for i in range(1, 100):
        age_lo = rnd.randint(18, 80)
        amount_lo = rnd.randrange(0, 90000, 1000)
        rules.append({
            "age": [age_lo, min(99, age_lo + rnd.randint(10, 40))],
            "amount": [amount_lo, amount_lo + rnd.randrange(5000, 40000, 1000)],
            "country": rnd.choice(COUNTRIES) if rnd.random() < 0.6 else None,
            "customerType": rnd.choice(TYPES) if rnd.random() < 0.5 else None,
            "fee": i,
        })
    rules.append({"age": None, "amount": None, "country": None, "customerType": None, "fee": 1000})
    return rules


def feel_dmn(rules, num_type, c7=False):
    """DMN 1.3 with FEEL unary tests; inputData + requirements so Kogito's validator accepts the model.
    c7: the C7 forks refuse to deploy a decision without history time to live (like the process)."""
    ttl = ' xmlns:camunda="http://camunda.org/schema/1.0/dmn"' if c7 else ""
    dec_ttl = ' camunda:historyTimeToLive="P1D"' if c7 else ""
    inputs = [("age", num_type), ("amount", num_type), ("country", "string"), ("customerType", "string")]
    def cell(rule, name):
        v = rule[name]
        if v is None:
            return "-"
        return f"[{v[0]}..{v[1]}]" if isinstance(v, list) else f'"{v}"'
    rows = "\n".join(
        f'      <rule id="Rule_{k}">'
        + "".join(f'<inputEntry id="In_{k}_{j}"><text>{cell(r, n)}</text></inputEntry>' for j, (n, _) in enumerate(inputs))
        + f'<outputEntry id="Out_{k}"><text>{r["fee"]}</text></outputEntry></rule>'
        for k, r in enumerate(rules, 1))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Scenario C: generated by load/gen-pricing-dmn.py, do not edit. 100 rules, COLLECT + SUM: every rule is evaluated. -->
<definitions xmlns="https://www.omg.org/spec/DMN/20191111/MODEL/" id="Definitions_Pricing" name="pricing" namespace="{NS}"{ttl}>
{"".join(f'''  <inputData id="InputData_{n}" name="{n}"><variable id="Var_{n}" name="{n}" typeRef="{t}"/></inputData>
''' for n, t in inputs)}  <decision id="Pricing" name="fee"{dec_ttl}>
    <variable id="Var_fee" name="fee" typeRef="{num_type}"/>
{"".join(f'''    <informationRequirement id="Req_{n}"><requiredInput href="#InputData_{n}"/></informationRequirement>
''' for n, _ in inputs)}    <decisionTable id="Table_Pricing" hitPolicy="COLLECT" aggregation="SUM">
{"".join(f'''      <input id="Input_{n}" label="{n}"><inputExpression id="Expr_{n}" typeRef="{t}"><text>{n}</text></inputExpression></input>
''' for n, t in inputs)}      <output id="Output_fee" name="fee" typeRef="{num_type}"/>
{rows}
    </decisionTable>
  </decision>
</definitions>
"""


def flowable_dmn(rules):
    """Flowable DMN: unary tests like '>= 18' / '== "DE"', so each range becomes two columns."""
    cols = [("age", ">=", 0), ("age", "<=", 1), ("amount", ">=", 0), ("amount", "<=", 1),
            ("country", "==", None), ("customerType", "==", None)]
    def cell(rule, name, op, idx):
        v = rule[name]
        if v is None:
            return "-"
        return f"{op} {v[idx]}" if idx is not None else f'{op} "{v}"'
    rows = "\n".join(
        f'      <rule id="Rule_{k}">'
        + "".join(f"<inputEntry id=\"In_{k}_{j}\"><text><![CDATA[{cell(r, n, op, idx)}]]></text></inputEntry>"
                  for j, (n, op, idx) in enumerate(cols))
        + f'<outputEntry id="Out_{k}"><text>{r["fee"]}</text></outputEntry></rule>'
        for k, r in enumerate(rules, 1))
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<definitions xmlns="https://www.omg.org/spec/DMN/20191111/MODEL/" id="Definitions_Pricing" name="pricing" namespace="{NS}">
  <!-- Scenario C: generated by load/gen-pricing-dmn.py, do not edit. 100 rules, COLLECT + SUM: every rule is evaluated.
       Comment inside the root: Flowable's StAX parser fails on a comment before it. -->
  <decision id="Pricing" name="fee">
    <decisionTable id="Table_Pricing" hitPolicy="COLLECT" aggregation="SUM">
{"".join(f'''      <input id="Input_{j}" label="{n}{ {'>=': ' min', '<=': ' max'}.get(op, '') }"><inputExpression id="Expr_{j}" typeRef="{"string" if idx is None else "number"}"><text>{n}</text></inputExpression></input>
''' for j, (n, op, idx) in enumerate(cols))}      <output id="Output_fee" name="fee" typeRef="number"/>
{rows}
    </decisionTable>
  </decision>
</definitions>
"""


def expected_fee(rules, age, amount, country, customer_type):
    def hit(r):
        return ((r["age"] is None or r["age"][0] <= age <= r["age"][1])
                and (r["amount"] is None or r["amount"][0] <= amount <= r["amount"][1])
                and r["country"] in (None, country) and r["customerType"] in (None, customer_type))
    return sum(r["fee"] for r in rules if hit(r))


if __name__ == "__main__":
    rules = make_rules()
    # self-check: the catch-all rule always hits, and a typical request hits a few random rules too
    rnd = random.Random(1)
    sample = [expected_fee(rules, rnd.randint(18, 99), rnd.randint(0, 100000), rnd.choice(COUNTRIES), rnd.choice(TYPES))
              for _ in range(10000)]
    assert min(sample) >= 1000
    print(f"avg hits besides catch-all: fee sum avg {sum(sample) / len(sample) - 1000:.0f}, "
          f"requests with >1 hit: {sum(s > 1000 for s in sample) / len(sample):.0%}")

    files = {
        "load/scenario-c-rules.json": json.dumps(rules, indent=None),
        "apps/cibseven/src/main/resources/pricing.dmn": feel_dmn(rules, "integer", c7=True),
        "apps/operaton/src/main/resources/pricing.dmn": feel_dmn(rules, "integer", c7=True),
        "apps/kogito/src/main/resources/pricing.dmn": feel_dmn(rules, "number"),
        "apps/kogito-kafka/src/main/resources/pricing.dmn": feel_dmn(rules, "number"),
        "apps/kogito-sb/src/main/resources/pricing.dmn": feel_dmn(rules, "number"),
        "k8s/camunda8/pricing.dmn": feel_dmn(rules, "number"),
        "apps/flowable/src/main/resources/dmn/pricing.dmn": flowable_dmn(rules),
    }
    for path, text in files.items():
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        Path(path).write_text(text, encoding="utf-8")
        print("wrote", path)
